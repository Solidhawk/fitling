// Makes the web app's texts, colours and images from the iOS app's own files, so there is one source (D-24).
// Run from web/: `node scripts/generate.mjs`. Writes src/generated/ and the image folders in public/.
import { copyFile, mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { basename, join } from "node:path";
import { fileURLToPath } from "node:url";

const languages = ["nl", "en", "de"];

/** A format code of the catalog: printf's conversions and Apple's %@, numbered or not. */
const formatCode = /%(?:\d+\$)?(?:\.\d+)?(?:llu|lld|ld|lu|lf|[@diufegscxXop%])/g;
/** The ones i18n.ts fills in; any other would show on screen as it is. */
const filledIn = /^%(?:\d+\$)?(?:lld|@)$/;

/**
 * Texts per language: a string, or `{ one, other }` for a plural. Fails on any missing translation, and on a format
 * code that i18n.ts does not fill in.
 */
function strings(catalog) {
  const result = Object.fromEntries(languages.map((language) => [language, {}]));
  const missing = [];
  const unknown = [];
  const check = (key, language, text) => {
    for (const [code] of text.matchAll(formatCode)) if (!filledIn.test(code)) unknown.push(`${key} (${language}: ${code})`);
  };
  for (const [key, entry] of Object.entries(catalog.strings)) {
    for (const language of languages) {
      const localization = entry.localizations?.[language];
      const plural = localization?.variations?.plural;
      if (plural?.one?.stringUnit && plural?.other?.stringUnit) {
        result[language][key] = { one: plural.one.stringUnit.value, other: plural.other.stringUnit.value };
        check(key, language, plural.one.stringUnit.value);
        check(key, language, plural.other.stringUnit.value);
      } else if (localization?.stringUnit) {
        result[language][key] = localization.stringUnit.value;
        check(key, language, localization.stringUnit.value);
      } else {
        missing.push(`${key} (${language})`);
      }
    }
  }
  if (missing.length > 0) throw new Error(`Missing translations: ${missing.join(", ")}`);
  if (unknown.length > 0) throw new Error(`Format codes the app does not fill in: ${unknown.join(", ")}`);
  return result;
}

/** "0xEF" or "0.937" to two hex digits. */
function channel(component) {
  const value = component.startsWith("0x") ? parseInt(component.slice(2), 16) : Math.round(parseFloat(component) * 255);
  return value.toString(16).padStart(2, "0");
}

/** #rrggbb, or #rrggbbaa when the colour is see-through (a shadow). */
function hex({ red, green, blue, alpha = "1" }) {
  const opacity = parseFloat(alpha);
  const rgb = `#${channel(red)}${channel(green)}${channel(blue)}`;
  return opacity >= 1 ? rgb : rgb + Math.round(opacity * 255).toString(16).padStart(2, "0");
}

/** "PartnerRibbon/owl" to "--partner-ribbon-owl". */
function variable(name) {
  return `--${name.replace(/\//g, "-").replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase()}`;
}

async function colorsets(folder, prefix = "") {
  const found = [];
  for (const entry of await readdir(folder, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    if (entry.name.endsWith(".colorset")) {
      const contents = JSON.parse(await readFile(join(folder, entry.name, "Contents.json"), "utf8"));
      const light = contents.colors.find((color) => !color.appearances);
      const dark = contents.colors.find((color) => color.appearances?.some((appearance) => appearance.value === "dark"));
      found.push({
        name: prefix + entry.name.replace(/\.colorset$/, ""),
        light: hex(light.color.components),
        dark: hex((dark ?? light).color.components),
      });
    } else if (!entry.name.endsWith(".imageset")) {
      found.push(...(await colorsets(join(folder, entry.name), `${prefix}${entry.name}/`)));
    }
  }
  return found;
}

function css(colors) {
  const block = (pick) => colors.map((color) => `  ${variable(color.name)}: ${pick(color)};`).join("\n");
  return `/* Generated by scripts/generate.mjs from the colorsets of the iOS app. Do not edit. */
:root {
${block((color) => color.light)}
}

@media (prefers-color-scheme: dark) {
  :root {
${block((color) => color.dark).replace(/^/gm, "  ")}
  }
}
`;
}

async function fresh(folder) {
  await rm(folder, { recursive: true, force: true });
  await mkdir(folder, { recursive: true });
}

/** Every file in the image sets below `folder` whose name ends with `extension`. */
async function imagesetFiles(folder, extension) {
  const found = [];
  for (const entry of await readdir(folder, { withFileTypes: true, recursive: true })) {
    if (entry.isFile() && entry.name.endsWith(extension) && entry.parentPath.endsWith(".imageset")) {
      found.push(join(entry.parentPath, entry.name));
    }
  }
  return found;
}

export async function generate({ resources, out }) {
  const generated = join(out, "src/generated");
  await mkdir(generated, { recursive: true });

  const catalog = JSON.parse(await readFile(join(resources, "Localizable.xcstrings"), "utf8"));
  await writeFile(join(generated, "strings.json"), JSON.stringify(strings(catalog)));
  await writeFile(join(generated, "colors.css"), css(await colorsets(join(resources, "Assets.xcassets"))));
  await copyFile(join(resources, "PartnerAnchors.json"), join(generated, "partnerAnchors.json"));

  const partners = join(out, "public/partners");
  await fresh(partners);
  for (const file of await imagesetFiles(join(resources, "Partners.xcassets"), ".png")) {
    await copyFile(file, join(partners, basename(file)));
  }

  const exercises = join(out, "public/exercises");
  await fresh(exercises);
  for (const name of await readdir(join(resources, "ExerciseAnimations"))) {
    await copyFile(join(resources, "ExerciseAnimations", name), join(exercises, name));
  }

  // Recipe photos are partly CC BY (docs/BRONNEN.md): each goes online with its credit, which the recipe
  // screen shows under it.
  const recipes = join(out, "public/recipes");
  await fresh(recipes);
  for (const file of await imagesetFiles(join(resources, "Assets.xcassets/Recipes"), ".jpg")) {
    const id = basename(join(file, "..")).replace(/\.imageset$/, "").toLowerCase();
    await copyFile(file, join(recipes, `${id}.jpg`));
  }
  const catalogRecipes = JSON.parse(await readFile(join(resources, "RecipeCatalog.json"), "utf8")).recipes;
  const credits = Object.fromEntries(
    catalogRecipes.filter((recipe) => recipe.photoCredit).map((recipe) => [recipe.id.toLowerCase(), recipe.photoCredit]),
  );
  await writeFile(join(generated, "recipeCredits.json"), JSON.stringify(credits));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const web = fileURLToPath(new URL("..", import.meta.url));
  await generate({ resources: join(web, "../Fitling/Resources"), out: web });
}
