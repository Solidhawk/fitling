"""Writes Sources/FitlingCore/FoldTable.swift: for every letter of the Latin, Greek and Cyrillic blocks with a
canonical decomposition, what is left after the combining marks are dropped. `String.folded` uses it, so it
gives what Foundation's NFD gave, without Foundation (D-24). Canonical decompositions never change (Unicode
stability policy), so the table does not go stale.

Run from Packages/FitlingCore: python Scripts/fold-table.py
"""
import unicodedata
from collections import defaultdict
from pathlib import Path

RANGES = [(0x00C0, 0x0250), (0x0370, 0x0500), (0x1E00, 0x2000)]

def escaped(text):
    return "".join("\\u{%X}" % ord(c) for c in text)

groups = defaultdict(str)
for start, end in RANGES:
    for value in range(start, end):
        letter = chr(value)
        base = "".join(c for c in unicodedata.normalize("NFD", letter) if unicodedata.category(c) != "Mn")
        if base != letter:
            groups[base] += letter

lines = [f'            ("{escaped(base)}", "{escaped(letters)}"),' for base, letters in sorted(groups.items())]
source = f"""// Generated by Scripts/fold-table.py from Unicode's canonical decompositions. Do not edit.

extension String {{
    /// Letters of U+00C0–U+024F, U+0370–U+04FF and U+1E00–U+1FFF to what NFD leaves of them without combining marks.
    static let foldTable: [Unicode.Scalar: String] = {{
        let groups: [(String, String)] = [
{chr(10).join(lines)}
        ]
        var table: [Unicode.Scalar: String] = [:]
        for (base, letters) in groups {{
            for letter in letters.unicodeScalars {{ table[letter] = base }}
        }}
        return table
    }}()
}}
"""
Path("Sources/FitlingCore/FoldTable.swift").write_text(source, encoding="utf-8", newline="\n")
print(sum(len(v) for v in groups.values()), "letters in", len(groups), "groups")
